"use client";

/**
 * App Store配布のiOSアプリ内で、Stripe決済ボタンの代わりに出す案内。
 *
 * 2026-09-27のApple審査ガイドライン3.1.1の却下で、「App内課金以外で購入できる
 * デジタルコンテンツにアクセスできるのに、外部への案内・リンクを出している」こと自体が
 * 違反だと明確に指摘された(以前のバージョンは「ウェブ版でご登録ください」というリンク付き
 * 案内を表示していたが、これがまさに指摘対象)。
 *
 * 対応: iOSアプリ内では、購入・契約管理に関する外部への言及(リンクはもちろん、
 * 「ウェブ版から」といった文言も含む)を一切出さない。単に「このアプリでは利用できない」
 * という中立的な状態表示のみにとどめる。既に加入済みのユーザーの機能アクセス自体は
 * 変更していない(このコンポーネントは未加入者への案内、または加入者向けの契約管理導線の
 * 代わりに出るだけで、加入済みなら棋譜解析等の機能はそのまま使える)。
 */
export function IOSWebBillingNotice({
  variant = "pricing",
}: {
  /** "pricing": 加入前の案内文言 / "manage": 契約管理の案内文言 */
  variant?: "pricing" | "manage";
}) {
  return (
    <div className="mt-5 rounded-2xl border border-line-strong bg-n-4/60 p-4 text-center">
      <p className="text-[13px] font-bold text-fg">
        {variant === "manage" ? "契約の管理はこのアプリでは行えません" : "使い放題プランはこのアプリでは現在ご利用いただけません"}
      </p>
    </div>
  );
}
