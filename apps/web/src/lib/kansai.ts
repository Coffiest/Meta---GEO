/**
 * 解説の文章を、ラフくん(相手の決定を解説するキャラクター)の関西弁にする。
 *
 * 解説の中身はバリィと全く同じ(オーナー確定)。言い回しだけを関西弁にする。
 * 解説の文章は知識ベース・コーチのルール・スポットの表などから組み立てられ、量が多いので、
 * 1文ずつ書き直すのではなく、バリィの口調(〜だよ / 〜だね / 〜しよう …)を規則で置き換える。
 * 規則は上から順に当てる(長い言い回しを先に)。ポーカー用語・数字・カードの表記には触れない。
 */
const RULES: [RegExp, string][] = [
  // 文末の口調
  [/ですよね/g, "やんな"],
  [/ですよ/g, "やで"],
  [/ですね/g, "やな"],
  [/でしょう/g, "やろ"],
  [/だよね/g, "やんな"],
  [/だよ/g, "やで"],
  [/だね/g, "やな"],
  [/だった/g, "やった"],
  [/なんだ([。！、])/g, "なんや$1"],
  [/んだ([。！、])/g, "んや$1"],
  [/だ([。！、])/g, "や$1"],
  [/じゃない/g, "ちゃう"],
  [/ではない/g, "ちゃう"],
  [/だから、/g, "せやから、"],
  [/しかし、/g, "せやけど、"],
  // 否定(動詞の「〜ない」→「〜へん」)
  [/しないといけない/g, "せなあかん"],
  [/ないといけない/g, "なあかん"],
  [/いけない/g, "あかん"],
  [/しないと/g, "せんと"],
  [/しかない/g, "しかあらへん"],
  [/ていない/g, "てへん"],
  [/しない/g, "せえへん"],
  [/できない/g, "できへん"],
  [/こない/g, "けえへん"],
  [/わからない/g, "わからへん"],
  [/([かさたまらわ])ない/g, "$1へん"],
  [/りない/g, "りへん"],
  // 進行・完了
  [/している/g, "しとる"],
  [/ている/g, "とる"],
  [/ておく/g, "とく"],
  [/ちゃった/g, "てもうた"],
  [/てしまった/g, "てもうた"],
  [/てしまう/g, "てまう"],
  [/ので、/g, "から、"],
  [/しちゃう/g, "してまう"],
  // 言葉
  [/本当に/g, "ほんまに"],
  [/本当/g, "ほんま"],
  [/とても/g, "めっちゃ"],
  [/すごく/g, "めっちゃ"],
  [/どうして/g, "なんで"],
  [/いい手/g, "ええ手"],
  [/いい選択/g, "ええ選択"],
  [/いい場面/g, "ええ場面"],
  [/いいね/g, "ええな"],
  [/いいよ/g, "ええで"],
  [/してもいい/g, "してもええ"],
  [/でもいい/g, "でもええ"],
  [/ていい/g, "てええ"],
  [/しよう([。！])/g, "しよか$1"],
  [/みよう([。！])/g, "みよか$1"],
  [/ナイス！/g, "ナイスや！"],
  // 残った文末の「よ」「ね」
  [/よね([。！])/g, "よな$1"],
  [/よ([。！])/g, "で$1"],
  [/ね([。！])/g, "な$1"],
  // 置き換え同士がぶつかった形を整える
  [/へんんや/g, "へんねん"],
];

export function toKansai(text: string): string {
  let out = text;
  for (const [re, to] of RULES) out = out.replace(re, to);
  return out;
}
