/** 文章の一部分(ただの文字か、用語)。 */
export type TermSegment = { text: string; entry?: GlossaryEntry };

interface Matcher {
  word: string;
  entry: GlossaryEntry;
  ascii: boolean;
}

const ASCII_WORD = /^[A-Za-z0-9 +]+$/;
const ASCII_CHAR = /[A-Za-z0-9]/;

/** 見つける語を長い順に並べる(「トップペア」を「ペア」より先に、「3ベット」を「ベット」より先に)。 */
const MATCHERS: Matcher[] = REVIEW_GLOSSARY.flatMap((entry) =>
  [entry.term, ...(entry.aliases ?? [])].map((word) => ({ word, entry, ascii: ASCII_WORD.test(word) }))
).sort((a, b) => b.word.length - a.word.length);

/** 先頭の文字ごとに引けるようにしておく(文章を1文字ずつ見るときの候補)。 */
const BY_FIRST = new Map<string, Matcher[]>();
for (const m of MATCHERS) {
  const k = m.word[0]!;
  const list = BY_FIRST.get(k) ?? [];
  list.push(m);
  BY_FIRST.set(k, list);
}

/**
 * 文章を「ただの文字」と「用語」に分ける。左から見て、その位置で始まる最も長い用語を取る。
 * 同じ用語は文章ごとに最初の1回だけ印を付ける(全部に下線を引くと読みにくい。Wikipedia のリンクと同じ)。
 * `seen` を渡すと、複数の文章で「最初の1回」を共有する(渡した Set に見つけた用語を足す)。
 */
export function splitTerms(text: string, seen: Set<GlossaryEntry> = new Set()): TermSegment[] {
  const out: TermSegment[] = [];
  let plain = "";
  let i = 0;
  while (i < text.length) {
    const hit = (BY_FIRST.get(text[i]!) ?? []).find((m) => {
      if (!text.startsWith(m.word, i)) return false;
      if (!m.ascii) return true;
      // 英字の用語は、前後が英数字なら別の語の一部(40BB・ChipEV・CBS など)。
      const before = text[i - 1];
      const after = text[i + m.word.length];
      return !(before && ASCII_CHAR.test(before)) && !(after && ASCII_CHAR.test(after));
    });
    if (hit && !seen.has(hit.entry)) {
      if (plain) out.push({ text: plain });
      plain = "";
      out.push({ text: hit.word, entry: hit.entry });
      seen.add(hit.entry);
      i += hit.word.length;
    } else if (hit) {
      // 2回目以降はただの文字(ただし長い語ごと飛ばし、中の短い語を拾い直さない)。
      plain += hit.word;
      i += hit.word.length;
    } else {
      plain += text[i];
      i += 1;
    }
  }
  if (plain) out.push({ text: plain });
  return out;
}

/** 複数の文章を順に分け、同じ用語は全体で最初の1回だけ印を付ける(「詳しく見る」の要点と本文など)。 */
export function splitTermsMany(texts: string[]): TermSegment[][] {
  const seen = new Set<GlossaryEntry>();
  return texts.map((t) => splitTerms(t, seen));
}
